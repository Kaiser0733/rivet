#!/usr/bin/env python3
"""Generate Rivet's bundled model-limit table from models.dev.

The app never fetches this at runtime. Run this script when refreshing the
snapshot, then commit both the script output and the updated date.

Usage:
    python3 scripts/generate_model_limits.py --source /tmp/api.json
    python3 scripts/generate_model_limits.py            # fetches models.dev

The input is the models.dev API document: provider -> models -> limit.
Only text-output models with a positive context limit are kept. Two kinds of
row are written:

    *       <model>  <context> <output>   canonical fallback
    <key>   <model>  <context> <output>   provider-scoped entry

Canonical rows take the minimum context/output across providers, because a
model served through a smaller route must not be planned at the larger one.
"""
from __future__ import annotations

import argparse
import datetime as _dt
import json
import sys
import urllib.request
from pathlib import Path
from typing import Any

SOURCE_URL = "https://models.dev/api.json"
# Provider keys we keep. Everything else still contributes to the canonical
# rows, but is not matched provider-scoped (Rivet has no way to identify it).
PROVIDER_KEYS = {
    "openai", "anthropic", "google", "google-vertex", "deepseek", "openrouter",
    "groq", "mistral", "togetherai", "fireworks-ai", "cerebras", "xai", "meta",
    "qwen", "moonshotai", "zai", "cohere", "perplexity", "ai21", "nvidia",
    "amazon-bedrock",
}
OUTPUT = Path("app/src/main/resources/model-limits.tsv")


def text_model(model: dict[str, Any]) -> bool:
    outputs = ((model.get("modalities") or {}).get("output") or [])
    return "text" in outputs


def positive(value: Any) -> int | None:
    if isinstance(value, bool):
        return None
    if isinstance(value, int):
        return value if value > 0 else None
    return None


def collect(document: dict[str, Any]) -> tuple[list[tuple[str, str, int, int | None]], list[str]]:
    """Return (provider-scoped rows, canonical ids) deterministically."""
    scoped: dict[tuple[str, str], tuple[str, str, int, int | None]] = {}
    canonical: dict[str, list[tuple[int, int | None]]] = {}
    skipped = 0
    for provider, payload in document.items():
        models = (payload or {}).get("models") or {}
        if not isinstance(models, dict):
            continue
        for model_id, model in models.items():
            if not isinstance(model, dict) or not text_model(model):
                skipped += 1
                continue
            limit = model.get("limit") or {}
            context = positive(limit.get("context"))
            if context is None:
                skipped += 1
                continue
            output = positive(limit.get("output"))
            canonical.setdefault(model_id, []).append((context, output))
            if provider in PROVIDER_KEYS:
                scoped[(provider, model_id)] = (provider, model_id, context, output)
    rows = sorted(scoped.values(), key=lambda row: (row[0], row[1].lower()))
    for model_id, values in canonical.items():
        context = min(value[0] for value in values)
        outputs = [value[1] for value in values if value[1] is not None]
        output = min(outputs) if outputs else None
        rows.append(("*", model_id, context, output))
    rows.sort(key=lambda row: (row[0] != "*", row[0], row[1].lower()))
    return rows, [model_id for model_id, _ in sorted(canonical.items())]


def render(rows: list[tuple[str, str, int, int | None]], generated: str) -> str:
    lines = [
        "# Rivet model-limit snapshot. Generated by scripts/generate_model_limits.py.",
        f"# source: {SOURCE_URL}",
        f"# generated: {generated}",
        "# licence: MIT (models.dev); see licenses/models.dev-MIT.txt",
        "# provider\tmodel\tcontext\toutput",
    ]
    for provider, model_id, context, output in rows:
        lines.append(f"{provider}\t{model_id}\t{context}\t{'' if output is None else output}")
    return "\n".join(lines) + "\n"


def load(source: str | None) -> dict[str, Any]:
    if source:
        return json.loads(Path(source).read_text())
    with urllib.request.urlopen(SOURCE_URL, timeout=120) as response:
        return json.loads(response.read())


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", help="local models.dev api.json")
    parser.add_argument("--output", default=str(OUTPUT))
    parser.add_argument("--generated", default=_dt.date.today().isoformat())
    args = parser.parse_args(argv)
    rows, _ = collect(load(args.source))
    target = Path(args.output)
    target.write_text(render(rows, args.generated))
    print(f"wrote {len(rows)} rows to {target}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
